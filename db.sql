CREATE TABLE `user` (id int(10) NOT NULL AUTO_INCREMENT, source_type_id int(10) NOT NULL, source_id int(10) NOT NULL, type varchar(255) NOT NULL, PRIMARY KEY (id));
CREATE TABLE artifact (id int(10) NOT NULL AUTO_INCREMENT, UUID binary(16) NOT NULL UNIQUE, `date` date NOT NULL, description varchar(255), user_id int(10) NOT NULL, PRIMARY KEY (id)) comment='If task_id is null, then this artifact is a personal project. Otherwise it is a task solution.';
CREATE TABLE evidence (id int(10) NOT NULL AUTO_INCREMENT, level tinyint NOT NULL, description varchar(255), competence_id int(10) NOT NULL, artifact_id int(10) NOT NULL, PRIMARY KEY (id));
CREATE TABLE competence (id int(10) NOT NULL AUTO_INCREMENT, concept_uri varchar(255) NOT NULL, skill_type varchar(255) NOT NULL, name varchar(255) NOT NULL UNIQUE, description varchar(255), PRIMARY KEY (id));
CREATE TABLE course (id int(10) NOT NULL AUTO_INCREMENT, source_type_id int(10) NOT NULL, source_id int(10) NOT NULL, PRIMARY KEY (id));
CREATE TABLE source_type (id int(10) NOT NULL AUTO_INCREMENT, name varchar(255) NOT NULL, PRIMARY KEY (id)) comment='This entity determines the source of an asset. The database doesn''t store all necessary information and must rely on outside sources. 
For instance user name, semester and various other info will be provided via USOS API. For debug purposes some users will be INTERNAL and stored directly in the database. 
Every entity that references this entity has an additional source_id field which is the asset id used by the source (USOS, INTERNAL). 
Since this is a table and not a fixed ENUM, additional source types can be implemented.';
CREATE TABLE task (id int(10) NOT NULL AUTO_INCREMENT, title varchar(255) NOT NULL, description varchar(255), creation_date date NOT NULL, due_date date NOT NULL, teacher_id int(10) NOT NULL, subject_id int(10) NOT NULL, PRIMARY KEY (id));
CREATE TABLE course_teacher (user_id int(10) NOT NULL, course_id int(10) NOT NULL);
CREATE TABLE artifact_queue (UUID binary(16) NOT NULL, `date` date NOT NULL, state ENUM('WAITING', 'IN_PROGRESS') NOT NULL, user_id int(10) NOT NULL, task_id int(10), PRIMARY KEY (UUID)) comment='If task_id is null, then this artifact is a personal project. Otherwise it is a task solution.';
CREATE TABLE task_artifact (task_id int(10) NOT NULL, artifact_id int(10) NOT NULL, PRIMARY KEY (task_id, artifact_id));
